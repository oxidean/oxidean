//! Emit `docs/openapi.yaml` from the REST route table — same document
//! `GET /api/v1/openapi.json` serves at runtime (single source of truth:
//! `oxidean-api/src/rest/spec.rs` + the `ROUTES` tables).

use std::path::PathBuf;

fn main() {
    // CARGO_MANIFEST_DIR = .../crates/oxidean-api → repo root is ../..
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = root.join("docs/openapi.yaml");

    let doc = oxidean_api::rest::spec::openapi_doc();
    let yaml = serde_yaml::to_string(&doc).expect("serialize openapi doc");
    let rendered = format!(
        "# AUTO-GENERATED by `cargo run -p oxidean-api --bin openapi-gen` — do not edit by hand.\n{yaml}"
    );

    if let Some(first) = std::env::args().nth(1).as_deref() {
        match first {
            "--check" => {
                let existing = std::fs::read_to_string(&out).unwrap_or_default();
                if existing == rendered {
                    println!("docs/openapi.yaml is up to date");
                    return;
                }
                eprintln!("docs/openapi.yaml is stale — run `make openapi-gen`");
                std::process::exit(1);
            }
            other => {
                eprintln!("unknown arg {other:?} — usage: openapi-gen [--check]");
                std::process::exit(2);
            }
        }
    }

    std::fs::write(&out, rendered).expect("write docs/openapi.yaml");
    println!("wrote {}", out.display());
}
